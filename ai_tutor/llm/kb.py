RECURSION_FINE = """① 生活类比
   查纸质词典找生词：你查"拓朴"，释义里出现"同胚"，只好再查"同胚"；释义里又有"连续映射"，继续查……
   直到某个词的解释你全都认识（这就是"基准情形"），然后你沿着刚才的查询路径一层层回头，
   把每一层的解释补全，最后真正读懂了最初那个词。这个"往下钻 → 触底 → 往回补"的过程就是递归。
   （这里刻意不采用常见的「层层嵌套」式类比：那类比喻只有嵌套、缺少「触底后逐层回填」这一步，
     容易让人误以为递归只是外形上套用自身。）

② 技术定义
   递归：一个过程（函数）在自身的定义中直接或间接地调用自身，把原问题分解为规模更小的同类子问题，
   直到遇到可直接求解的基准情形（base case），再逐层返回并组合结果。递归必须具备终止性。

③ 结构图解（递归的"往下钻 → 触底 → 往回补"）
   调用链示意（左侧递推压栈，右侧回代出栈）：
        factorial(3)
          └─ 3 × factorial(2)          ← 递推：压栈，等待子结果
                └─ 2 × factorial(1)    ← 递推：继续压栈
                      └─ return 1      ← 触底：命中基准情形
                ← 2 × 1 = 2            ← 回代：逐层出栈回填
          ← 3 × 2 = 6                  ← 回代：最外层得到结果
   与"栈"结构的关系：后进先出（LIFO）——最后压入的 factorial(1) 最先返回，
   这也是递归占用的额外空间的来源（栈深度 = 递归层数）。

④ 代码示例（Python，逐行注释）
   def factorial(n):
       if n <= 1:              # 基准情形：规模已小到可以直接给出答案，递归在此"触底"
           return 1            # 不再调用自身，否则将无限递归导致 RecursionError / 栈溢出
       return n * factorial(n - 1)   # 递归情形：把 n! 化为 n * (n-1)!，规模每次减 1，保证收敛

⑤ 执行过程模拟表（factorial(3)）—— 递推压栈 / 触底 / 回代逐层展开
   ┌──────┬───────────────────────┬──────────────────────────────┐
   │ 阶段 │ 调用/状态             │ 说明                         │
   ├──────┼───────────────────────┼──────────────────────────────┤
   │ 递推 │ fact(3) = 3 * fact(2) │ 压栈，未求值                 │
   │ 递推 │  ↳ fact(2) = 2 * fact(1) │ 压栈，未求值              │
   │ 触底 │  ↳ fact(1) → return 1 │ 命中基准情形，开始返回       │
   │ 回代 │ fact(2) = 2 * 1 = 2   │ 第一层回填                   │
   │ 回代 │ fact(3) = 3 * 2 = 6   │ 逐层回填完毕，出栈           │
   │ 结果 │ factorial(3) → 6      │ 与迭代法 3*2*1=6 一致        │
   └──────┴───────────────────────┴──────────────────────────────┘

⑤ 逐行执行过程对照（factorial(3) 代入代码）
   ┌──────┬────────────────────────┬──────┬──────────────────────────────┐
   │ 层级 │ 代码执行               │ 变量 │ 说明                         │
   ├──────┼────────────────────────┼──────┼──────────────────────────────┤
   │ 第1层│ factorial(3) → 3*f(2)  │ n=3  │ n>1，进入 else 分支，挂起等待 │
   │ 第2层│ factorial(2) → 2*f(1)  │ n=2  │ n>1，继续压栈                │
   │ 第3层│ factorial(1) → return 1│ n=1  │ n<=1 命中基准情形，直接返回  │
   │ 回代 │ 2 * 1 = 2              │ n=2  │ 第2层出栈，结果回填          │
   │ 回代 │ 3 * 2 = 6              │ n=3  │ 第1层出栈，结果回填          │
   │ 最终 │ factorial(3) = 6       │ —    │ 与迭代 3*2*1=6 一致          │
   └──────┴────────────────────────┴──────┴──────────────────────────────┘

⑥ 关键三要素
   1) 基准情形：能直接给出答案、不再递归的最小规模（如 n <= 1）。
   2) 递归情形：把原问题分解为同类但更小的子问题，并说明如何组合子结果。
   3) 收敛性：每一步都严格向基准情形靠近（本题中 n 每次减 1），否则不终止。

⑦ 初学者常见误区
   误区一：只写递归情形、漏掉基准情形 → 无限递归，报 RecursionError 或爆栈。
   误区二：以为"递归一定比循环好/快" → 递归有函数调用与栈空间开销，且朴素递归常含大量重复子问题
           （如 fib(n) = fib(n-1) + fib(n-2) 的时间复杂度为指数级）。

⑧ 不确定/争议标注
   递归与迭代没有绝对优劣：函数式编程（如 Haskell、Scheme）以递归为核心表达手段，
   工程实践中因栈深度限制与性能考虑常改写为迭代或加记忆化。选择取决于问题结构、数据规模与可读性权衡。"""

