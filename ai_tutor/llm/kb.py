LIMIT_LIMIT_ANSWER = "-1/6"

LIMIT_FINE = """【题型判断】当 x→0 时 sin x ~ x，故分子 sin x − x 是比 x 更高阶的无穷小，分母 x³ 为三阶无穷小，属于 0/0 型未定式（且为可去型）。
【方法选择】
  主选：洛必达法则（连续 3 次适用）。理由：分子分母在 x=0 的某去心邻域内可导，且每步仍满足 0/0 型，条件逐次复核通过。
  备选：泰勒（麦克劳林）展开。理由：分子只需展开到 x³ 项即可直接得到极限，计算量最小。
【分步求解】
  第 1 次：分子求导 cos x − 1，分母求导 3x²，得 (cos x − 1)/(3x²)，仍为 0/0 型。
  第 2 次：分子求导 −sin x，分母求导 6x，得 (−sin x)/(6x)，仍为 0/0 型。
  第 3 次：分子求导 −cos x，分母求导 6，得 (−cos x)/6；代入 x=0 得 −1/6，此时已非未定式，停止使用洛必达。
  结论：lim(x→0)(sin x − x)/x³ = −1/6。
【交叉验证】泰勒展开法：sin x = x − x³/6 + o(x³)，故 sin x − x = −x³/6 + o(x³)，
  原式 = [−x³/6 + o(x³)]/x³ = −1/6 + o(1) → −1/6。两种方法结果一致。
【易错点】
  ① 把 sin x 直接整体等价替换为 x 后得 (x − x)/x³ = 0，忽略了三阶项，属典型错误；
  ② 使用洛必达前必须逐步确认"仍为 0/0（或 ∞/∞）型"，第 3 次后代入了确定值就不能再求导；
  ③ 本题恰好需要 3 次；做完 2 次后若误判为"极限不存在"或"趋于 0"即错。
【不确定标注】本题解法唯一、结果确定，无争议。边界提示：若把条件改为 x→∞（如 (sin x − x)/x³ 无对应无穷小关系），
  洛必达法则不再适用，须改用有界量乘无穷小等思路。"""

