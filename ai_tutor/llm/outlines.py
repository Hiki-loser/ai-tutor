OUTLINE_STYLE_A = """高等数学 · 多元函数微分学 期末复习提纲（组织方式 A：概念 → 题型 → 易错点）

一、重点概念
  1. 偏导数：f_x(x₀,y₀) 是沿 x 方向的变化率，注意它是"固定其余变量"的一元导数。
  2. 全微分：dz = f_x dx + f_y dy，可微 ⇒ 偏导存在，反之不成立。
  3. 方向导数与梯度：方向导数 = grad f · e_l；梯度方向是函数增长最快的方向。
  4. 多元复合函数与隐函数求导：链式法则、隐函数存在定理。
  5. 极值与条件极值：无约束极值（Hessian 判别）、拉格朗日乘数法。

二、典型题型
  · 求偏导与全微分（含抽象复合函数）
  · 判断可微性 / 连续性与偏导存在性的关系
  · 求方向导数、梯度与曲线/曲面切向量、切平面、法线
  · 求无条件极值；用拉格朗日乘数法求条件极值（如"体积最大"类应用题）
  · 几何应用：空间曲线切线、曲面切平面与法平面

三、易错点
  · 误以为"偏导存在 ⇒ 可微"或"偏导连续 ⇔ 可微"（正确：偏导连续 ⇒ 可微 ⇒ 偏导存在）。
  · 抽象函数求二阶混合偏导时漏项（f₁₁、f₁₂、f₂₂ 都要写全）。
  · 拉格朗日乘数法构造 L 后，忘记同时解出 λ 与约束方程。
  · 条件极值只求驻点，未比较边界或端点情况。

复习节奏：先过概念与判别关系（1 天），再做题型专项（2 天），最后整理错题与易错点回看（1 天）。"""

OUTLINE_STYLE_B = """高等数学 · 多元函数微分学 期末复习提纲（组织方式 B：按"考试能力"倒推）

【能力 1】把多元问题化成熟悉的一元问题
  → 需要：偏导数定义、链式法则、隐函数求导公式
  → 练习：对 z = f(u,v)、u=u(x,y) 的结构做全微分展开，训练"画依赖图再求导"

【能力 2】判断函数的"光滑程度"（连续性 / 偏导 / 可微 / 偏导连续）
  → 记忆链条：偏导连续 ⇒ 可微 ⇒ 连续且偏导存在；其余箭头均不成立
  → 高频反例：f(x,y)=xy/√(x²+y²) 类分段函数在原点处的可微性判定
  → 练习策略：每遇到一个分段函数，固定按"先查连续 → 再用定义查偏导 → 最后用定义查可微"三步走

【能力 3】几何量的计算
  → 三件套：方向导数与梯度、空间曲线切线、曲面切平面
  → 统一工具：法向量 n = (f_x, f_y, f_z)；方向导数 = 梯度与单位方向向量的内积

【能力 4】最值问题
  → 无约束：解 f_x=f_y=0，用 AC−B² 判别（>0 且 A>0 极小；>0 且 A<0 极大；<0 鞍点；=0 需另判）
  → 有约束：拉格朗日乘数法，注意约束个数与 λ 个数一致
  → 应用题：先设变量与目标函数，再明确约束，最后代回检验实际意义

【考前 48 小时清单】
  ① 默写可微性关系链条并各举一个反例；② 独立完成 3 道拉格朗日乘数法应用题；
  ③ 重新推导切平面与法线方程；④ 翻看错题本中"漏项"与"忘记约束"两类错误。

【易错点集中提醒】链式法则漏项、判别式 AC−B² 与二阶偏导符号混淆、条件极值忘记讨论边界。"""

OUTLINE_STYLE_C = """高等数学 · 多元函数微分学 期末复习提纲（组织方式 C：按题型分类 → 解法 → 陷阱）

▎题型一：直接求偏导与全微分
   解法步骤：固定其余变量 → 按一元求导 → 写出全微分表达式
   陷阱：把 ∂z/∂x 与 dz/dx 混为一谈；抽象函数不画依赖图导致漏项

▎题型二：判定可微性（定义法）
   解法步骤：先查 f 在点处是否连续 → 用定义算 f_x、f_y → 用定义验证
             Δz − (f_x Δx + f_y Δy) 是否为 o(ρ)
   陷阱：把"偏导存在"当成"可微"的充分条件；忽略 ρ = √(Δx²+Δy²) 的写法

▎题型三：几何应用（切平面 / 法线 / 方向导数）
   解法步骤：构造 F(x,y,z) = z − f(x,y) → 求梯度得法向量 → 代点写平面方程
   陷阱：法向量符号取反；方向导数忘记把方向向量单位化

▎题型四：无条件极值
   解法步骤：解驻点 → 算 A=f_xx、B=f_xy、C=f_yy → 用 AC−B² 判别 → 回代求极值
   陷阱：AC−B²=0 时直接下结论；忘记比较区域边界（闭区域最值问题）

▎题型五：条件极值（拉格朗日乘数法）
   解法步骤：写 L = f + λφ → 解方程组（含约束）→ 判断驻点是否为极值 → 结合实际意义取舍
   陷阱：方程组少解一个根；忘记"实际问题取最值时可只比较函数值"

▎通用应试策略
   遇到"是否一定/是否可能"类设问，先举反例再下结论；遇到分段函数一律回到定义；
   计算量大的题目先写出思路框架再动笔，避免白算。"""
